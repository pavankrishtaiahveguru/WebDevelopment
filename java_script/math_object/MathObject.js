// math object
let mathObject=Math;
// pi:piValue
console.log(mathObject.PI);
// pow(number):poweredNumber
console.log(mathObject.pow(10,2));
// sqrt(number):squareNumber
console.log(mathObject.sqrt(81));
// round(number):topRoundedNumber
console.log(mathObject.round(10.578));
// floor(number):bottomRoundedNumber
console.log(mathObject.floor(10.578));
// max(number):maximumNumber
console.log(mathObject.max(45,5,3,2,34,78,12,-10));
// min(number):minimumNumber
console.log(mathObject.min(45,5,3,2,34,78,12,-10));