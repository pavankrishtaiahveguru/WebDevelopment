// date object
let dateObjet=new Date();
// date time
console.log(dateObjet);
// getDate():date
console.log(dateObjet.getDate());
// getDay():dayCountNumber
console.log(dateObjet.getDay());
// getMount():mountCountNumber
console.log(dateObjet.getMonth());
// getHours():hours
console.log(dateObjet.getHours());
// getMinutes():minutes
console.log(dateObjet.getMinutes());
// toDateString():month/date/year
console.log(dateObjet.toDateString());
// toTimeString():hours-minutes-seconds
console.log(dateObjet.toTimeString());